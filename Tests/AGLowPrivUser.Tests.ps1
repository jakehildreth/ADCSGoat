BeforeAll {
    Add-Type -AssemblyName System.DirectoryServices
    . (Join-Path -Path $PSScriptRoot -ChildPath '..\Private\New-AGLowPrivUser.ps1')
    . (Join-Path -Path $PSScriptRoot -ChildPath '..\Private\Remove-AGLowPrivUser.ps1')
    . (Join-Path -Path $PSScriptRoot -ChildPath '..\Private\Test-AGLowPrivUserOwned.ps1')

    # A stand-in for a DirectoryEntry that records what was done to it.
    function New-FakeUserEntry {
        $properties = @{}
        foreach ($name in 'sAMAccountName', 'userPrincipalName', 'description', 'userAccountControl') {
            $properties[$name] = [pscustomobject]@{ Value = $null }
        }
        $entry = [pscustomobject]@{ Properties = $properties; Deleted = $false; Password = $null; FailPassword = $false }
        $entry | Add-Member -MemberType ScriptMethod -Name CommitChanges -Value { }
        $entry | Add-Member -MemberType ScriptMethod -Name DeleteTree -Value { $this.Deleted = $true }
        $entry | Add-Member -MemberType ScriptMethod -Name Invoke -Value {
            param($Method, $Value)
            if ($this.FailPassword) { throw 'password does not meet policy' }
            $this.Password = $Value
        }
        $entry
    }

    # A stand-in for a search hit. Description $null means the attribute is empty.
    function New-FakeSearchResult {
        param($Description, $Entry)
        $result = [pscustomobject]@{
            Properties = @{ description = @($Description) }
            Entry      = $Entry
        }
        $result | Add-Member -MemberType ScriptMethod -Name GetDirectoryEntry -Value { $this.Entry }
        $result
    }

    function Use-FakeDirectory {
        param($SearchResult, $NewUserEntry)
        $script:AddedUsers = [System.Collections.Generic.List[string]]::new()
        $script:FoundResult = $SearchResult
        $script:NewEntry = $NewUserEntry

        Mock -CommandName New-Object -ParameterFilter { $TypeName -eq 'System.DirectoryServices.DirectorySearcher' } -MockWith {
            $searcher = [pscustomobject]@{ SearchRoot = $null; Filter = $null; PropertiesToLoad = [System.Collections.ArrayList]::new() }
            $searcher | Add-Member -MemberType ScriptMethod -Name FindOne -Value { $script:FoundResult }
            $searcher
        }
        Mock -CommandName New-Object -ParameterFilter {
            $TypeName -eq 'System.DirectoryServices.DirectoryEntry' -and "$ArgumentList" -like '*CN=Users*'
        } -MockWith {
            $children = [pscustomobject]@{}
            $children | Add-Member -MemberType ScriptMethod -Name Add -Value {
                param($Name, $Schema)
                $script:AddedUsers.Add($Name)
                $script:NewEntry
            }
            [pscustomobject]@{ Children = $children }
        }
        Mock -CommandName New-Object -ParameterFilter {
            $TypeName -eq 'System.DirectoryServices.DirectoryEntry' -and "$ArgumentList" -notlike '*CN=Users*'
        } -MockWith {
            [pscustomobject]@{ defaultNamingContext = 'DC=adcs,DC=goat' }
        }
    }

    $securePassword = ConvertTo-SecureString -String 'Somepass1' -AsPlainText -Force
}

Describe 'New-AGLowPrivUser' {
    It 'Creates an enabled user carrying the ADCSGoat marker and the requested password' {
        $entry = New-FakeUserEntry
        Use-FakeDirectory -SearchResult $null -NewUserEntry $entry

        $created = New-AGLowPrivUser -UserName 'user' -Password $securePassword

        $created | Should -BeTrue
        $script:AddedUsers | Should -Be @('CN=user')
        $entry.Properties['description'].Value | Should -BeLike '*Generated by ADCSGoat*'
        $entry.Properties['sAMAccountName'].Value | Should -Be 'user'
        $entry.Properties['userPrincipalName'].Value | Should -Be 'user@adcs.goat'
        $entry.Properties['userAccountControl'].Value | Should -Be 512
        $entry.Password | Should -Be 'Somepass1'
        $entry.Deleted | Should -BeFalse
    }

    It 'Leaves an existing user untouched and warns' {
        $entry = New-FakeUserEntry
        Use-FakeDirectory -SearchResult (New-FakeSearchResult -Description 'someone elses' -Entry $null) -NewUserEntry $entry

        $created = New-AGLowPrivUser -UserName 'user' -Password $securePassword -WarningVariable warnings -WarningAction SilentlyContinue

        $created | Should -BeFalse
        $script:AddedUsers.Count | Should -Be 0
        $entry.Password | Should -BeNullOrEmpty
        "$warnings" | Should -BeLike '*already exists*'
    }

    It 'Deletes the half-created user when the password is rejected' {
        $entry = New-FakeUserEntry
        $entry.FailPassword = $true
        Use-FakeDirectory -SearchResult $null -NewUserEntry $entry

        { New-AGLowPrivUser -UserName 'user' -Password $securePassword } | Should -Throw '*password does not meet policy*'

        $entry.Deleted | Should -BeTrue
    }
}

Describe 'Remove-AGLowPrivUser' {
    It 'Deletes a user carrying the ADCSGoat marker' {
        $entry = New-FakeUserEntry
        Use-FakeDirectory -SearchResult (New-FakeSearchResult -Description 'Generated by ADCSGoat' -Entry $entry) -NewUserEntry $null

        Remove-AGLowPrivUser -UserName 'user' | Should -BeTrue

        $entry.Deleted | Should -BeTrue
    }

    It 'Keeps a user without the marker and warns' {
        $entry = New-FakeUserEntry
        Use-FakeDirectory -SearchResult (New-FakeSearchResult -Description 'Helpdesk account' -Entry $entry) -NewUserEntry $null

        $removed = Remove-AGLowPrivUser -UserName 'user' -WarningVariable warnings -WarningAction SilentlyContinue

        $removed | Should -BeFalse
        $entry.Deleted | Should -BeFalse
        "$warnings" | Should -BeLike '*was not created by ADCSGoat*'
    }

    It 'Keeps a user whose description is empty' {
        $entry = New-FakeUserEntry
        Use-FakeDirectory -SearchResult (New-FakeSearchResult -Description $null -Entry $entry) -NewUserEntry $null

        Remove-AGLowPrivUser -UserName 'user' -WarningAction SilentlyContinue | Should -BeFalse

        $entry.Deleted | Should -BeFalse
    }

    It 'Does nothing when the user does not exist' {
        Use-FakeDirectory -SearchResult $null -NewUserEntry $null

        Remove-AGLowPrivUser -UserName 'user' | Should -BeFalse
    }
}

Describe 'Test-AGLowPrivUserOwned' {
    It 'Is true for a user carrying the marker' {
        Use-FakeDirectory -SearchResult (New-FakeSearchResult -Description 'Generated by ADCSGoat' -Entry $null) -NewUserEntry $null

        Test-AGLowPrivUserOwned -UserName 'user' | Should -BeTrue
    }

    It 'Is false for a user without the marker' {
        Use-FakeDirectory -SearchResult (New-FakeSearchResult -Description 'Helpdesk account' -Entry $null) -NewUserEntry $null

        Test-AGLowPrivUserOwned -UserName 'user' | Should -BeFalse
    }

    It 'Is false when the user does not exist' {
        Use-FakeDirectory -SearchResult $null -NewUserEntry $null

        Test-AGLowPrivUserOwned -UserName 'user' | Should -BeFalse
    }
}
